-- Harden and extend first-party visitor intelligence.
-- This migration is intentionally additive and does not alter orders, customers or products.
begin;
-- Create the event store when this is the first visitor-intelligence migration.
create table if not exists public.visitor_events (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  event_type text not null,
  page_path text not null,
  referrer_host text,
  device_type text not null default 'unknown',
  product_slug text,
  created_at timestamptz not null default now()
);
alter table public.visitor_events enable row level security;
revoke all on table public.visitor_events from anon, authenticated;
grant select on table public.visitor_events to authenticated;
drop policy if exists visitor_events_staff_select on public.visitor_events;
create policy visitor_events_staff_select on public.visitor_events
  for select to authenticated using (public.is_staff_or_admin());
create index if not exists visitor_events_visitor_created_idx on public.visitor_events(visitor_id, created_at desc);
alter table public.visitor_events drop constraint if exists visitor_events_event_type_check;
alter table public.visitor_events add constraint visitor_events_event_type_check
  check (event_type in ('session_start','page_view','product_view','cart_view','checkout_view'));
create index if not exists visitor_events_device_created_idx on public.visitor_events(device_type, created_at desc);

create or replace function public.record_visitor_event(
  p_visitor_id uuid, p_event_type text, p_page_path text,
  p_referrer_host text default null, p_device_type text default 'unknown', p_product_slug text default null
)
returns boolean language plpgsql security definer set search_path = ''
as $$
declare v_recent_count integer;
begin
  if p_visitor_id is null
     or p_event_type not in ('session_start','page_view','product_view','cart_view','checkout_view')
     or p_page_path is null or char_length(p_page_path) not between 1 and 500
     or p_device_type not in ('mobile','desktop','tablet','unknown')
     or (p_referrer_host is not null and char_length(p_referrer_host)>255)
     or (p_product_slug is not null and char_length(p_product_slug)>160) then
    raise exception 'Invalid visitor event.' using errcode='22023';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(p_visitor_id::text, 0));
  select count(*) into v_recent_count from public.visitor_events
   where visitor_id=p_visitor_id and created_at > now() - interval '1 minute';
  if v_recent_count >= 30 then return false; end if;
  insert into public.visitor_events(visitor_id,event_type,page_path,referrer_host,device_type,product_slug)
  values(p_visitor_id,p_event_type,p_page_path,
    nullif(left(regexp_replace(coalesce(p_referrer_host,''),'[^a-zA-Z0-9.:-]','','g'),255),''),
    p_device_type,nullif(left(regexp_replace(coalesce(p_product_slug,''),'[^a-zA-Z0-9_-]','','g'),160),''));
  return true;
end;
$$;
revoke all on function public.record_visitor_event(uuid,text,text,text,text,text) from public;
grant execute on function public.record_visitor_event(uuid,text,text,text,text,text) to anon, authenticated;

create or replace function public.visitor_intelligence_summary(p_since timestamptz default null)
returns jsonb language plpgsql stable security definer set search_path = ''
as $$
declare v_result jsonb;
begin
  if auth.uid() is null or not public.is_staff_or_admin() then
    raise exception 'Staff access required.' using errcode='42501';
  end if;
  with filtered as (
    select * from public.visitor_events where p_since is null or created_at >= p_since
  ),
  sessions as (
    select visitor_id,
      count(*) filter (where event_type in ('page_view','product_view')) as page_count,
      min(created_at) as first_seen, max(created_at) as last_seen
    from filtered group by visitor_id
  ),
  session_first_touch as (
    select distinct on (visitor_id) visitor_id,
      coalesce(referrer_host,'Direct / None') as referrer_name,
      device_type
    from filtered
    order by visitor_id, created_at asc
  ),
  referrer_rows as (
    select referrer_name as name,count(*)::bigint as count
    from session_first_touch group by referrer_name order by count desc limit 8
  ),
  product_rows as (
    select coalesce(product_slug,page_path) as name,count(*)::bigint as count
    from filtered where event_type='product_view'
    group by coalesce(product_slug,page_path) order by count desc limit 8
  ),
  device_rows as (
    select device_type as name,count(*)::bigint as count
    from session_first_touch group by device_type order by count desc
  )
  select jsonb_build_object(
    'total_events',(select count(*) from filtered),
    'total_sessions',(select count(*) from sessions),
    'page_views',(select count(*) from filtered where event_type in ('page_view','product_view')),
    'product_views',(select count(*) from filtered where event_type='product_view'),
    'cart_views',(select count(*) from filtered where event_type='cart_view'),
    'checkout_views',(select count(*) from filtered where event_type='checkout_view'),
    'bounce_rate',coalesce((select round(100.0 * count(*) filter (where page_count <= 1) / nullif(count(*),0),1) from sessions),0),
    'avg_session_seconds',(select round(avg(extract(epoch from (last_seen-first_seen)))::numeric,1) from sessions where last_seen>first_seen),
    'referrers',coalesce((select jsonb_agg(jsonb_build_object('name',name,'count',count) order by count desc) from referrer_rows),'[]'::jsonb),
    'top_products',coalesce((select jsonb_agg(jsonb_build_object('name',name,'count',count) order by count desc) from product_rows),'[]'::jsonb),
    'devices',coalesce((select jsonb_agg(jsonb_build_object('name',name,'count',count) order by count desc) from device_rows),'[]'::jsonb)
  ) into v_result;
  return v_result;
end;
$$;
revoke all on function public.visitor_intelligence_summary(timestamptz) from public, anon;
grant execute on function public.visitor_intelligence_summary(timestamptz) to authenticated;
commit;
